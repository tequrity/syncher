export type MsgKey = keyof typeof en;

/** Looks up a UI string and fills in its `{placeholders}`. */
export function t(key: MsgKey, vars: Record<string, string | number> = {}): string {
	return en[key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}
